const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const core=require('../ui/qr-labels-core.js');
const sizing=require('../ui/sizing.js');
const inventory=JSON.parse(fs.readFileSync('./data/inventory.json','utf8'));
const records=inventory.products.map(p=>({...p,bundleKey:'drive-'+(p.stableFolderId||p.folderId)}));
const url=p=>'https://inventory.lucramarble.com/#bundle-'+encodeURIComponent(p.bundleKey);
const options={selectedOnly:false,selected:new Set(),includeReserved:true};
const all=core.prepare(records,options,sizing,url);
assert.equal(all.length,records.length);
if(records.some(p=>p.code==='L1010'))assert.equal(all[0].code,'L1010');
if(all.some(p=>p.code==='A3238'))assert.match(all.find(p=>p.code==='A3238').size,/^\d+ x \d+ cm$/);
assert.equal(core.prepare(records,{...options,selectedOnly:true},sizing,url).length,0);
const sample=records.find(p=>p.reserved);
assert.equal(core.prepare(records,{...options,selectedOnly:true,selected:new Set([sample.bundleKey])},sizing,url).length,1);
assert.equal(core.prepare(records,{...options,selectedOnly:true,selected:new Set([sample.bundleKey]),includeReserved:false},sizing,url).length,0);
assert.throws(()=>core.prepare(records,options,sizing,()=>url(records[0])));
assert.throws(()=>core.prepare([records[0],records[0]],options,sizing,url));
const missing={name:'Missing size',code:'TEST',bundleKey:'test',lines:[],dimensions:[]};
assert.equal(core.prepare([missing],options,sizing,url)[0].size,'Size not available');
const mixed={...missing,pcs:3,lines:[{widthCm:300,heightCm:150,pcs:2},{widthCm:160,heightCm:310,pcs:1}]};
assert.equal(core.prepare([mixed],options,sizing,url)[0].size,'153 x 303 cm');
assert.equal(core.prepare([{...mixed,pcs:4}],options,sizing,url)[0].partialSize,true);
const context={window:{}};vm.runInNewContext(fs.readFileSync('./ui/qr-label-assets.js','utf8'),context);
(async()=>{
 const {jsPDF}=require('../ui/vendor/jspdf.umd.min.js');const qrcode=require('../ui/vendor/qrcode.js');
 const doc=await core.create(all,context.window.LucraQRLabelAssets,{jsPDF,qrcode});
 assert.equal(doc.getNumberOfPages(),Math.ceil(records.length/6));
 const bytes=Buffer.from(doc.output('arraybuffer'));assert.equal(bytes.subarray(0,5).toString(),'%PDF-');if(process.env.LUCRA_PDF_TEST_OUTPUT)fs.writeFileSync(process.env.LUCRA_PDF_TEST_OUTPUT,bytes);
 const one=await core.create(all.slice(0,1),context.window.LucraQRLabelAssets,{jsPDF,qrcode});
 assert.equal(one.getNumberOfPages(),1);
 await assert.rejects(()=>core.create([],context.window.LucraQRLabelAssets,{jsPDF,qrcode}));
 console.log(`PASS: selection, reserved filtering, QR routing, missing/weighted sizes and ${all.length}-label PDF.`);
})().catch(error=>{console.error(error);process.exitCode=1;});
